/** Traduit un libellé venant de la base s'il est connu, sinon le renvoie tel quel. */
export const label = (d: Dict, raw: string) => d.labels[raw] ?? d.labels[raw.toLowerCase()] ?? raw;

/** Remplace {cle} dans un texte. */
export const fill = (text: string, values: Record<string, string | number>) =>
  text.replace(/\{(\w+)\}/g, (_, k) => String(values[k] ?? ""));
